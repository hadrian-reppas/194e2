// Regenerates src/lib/ratingImages.ts from the files under public/ratings.
//
// <Image> needs intrinsic width/height to work out an aspect ratio, and these
// files are static, so we read the dimensions once here rather than at runtime.
// Run via `npm run gen:images` (also wired into predev/prebuild).

import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

const PUBLIC_DIR = "public/ratings";
const OUT_FILE = "src/lib/ratingImages.ts";

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

function pngSize(buf) {
  // IHDR is the first chunk: width and height are big-endian u32 at byte 16.
  if (buf.subarray(1, 4).toString("ascii") !== "PNG") return null;
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

function svgSize(buf) {
  const head = buf.toString("utf8", 0, 2048);
  const attr = (name) => {
    const match = head.match(new RegExp(`<svg[^>]*\\s${name}="([^"]+)"`, "i"));
    if (!match) return null;
    const n = Number.parseFloat(match[1]);
    return Number.isFinite(n) ? n : null;
  };
  const width = attr("width");
  const height = attr("height");
  if (width && height) return { width, height };

  // No usable width/height attributes, so fall back to the viewBox extents.
  const viewBox = head.match(/<svg[^>]*\sviewBox="([^"]+)"/i);
  if (!viewBox) return null;
  const parts = viewBox[1].trim().split(/[\s,]+/).map(Number);
  if (parts.length !== 4 || parts.some((n) => !Number.isFinite(n))) return null;
  return { width: parts[2], height: parts[3] };
}

const entries = [];
const failures = [];

for (const file of walk(PUBLIC_DIR).sort()) {
  if (!/\.(png|svg)$/i.test(file)) continue; // .DS_Store and friends
  const buf = readFileSync(file);
  const size = file.endsWith(".png") ? pngSize(buf) : svgSize(buf);
  if (!size || !size.width || !size.height) {
    failures.push(file);
    continue;
  }
  const url = "/" + relative("public", file).split(sep).join("/");
  entries.push([url, size]);
}

if (failures.length > 0) {
  console.error(`Could not determine dimensions for:\n  ${failures.join("\n  ")}`);
  process.exit(1);
}

const body = entries
  .map(([url, { width, height }]) => `  "${url}": { width: ${width}, height: ${height} },`)
  .join("\n");

writeFileSync(
  OUT_FILE,
  `// GENERATED by scripts/gen-rating-images.mjs -- do not edit by hand.
// Run \`npm run gen:images\` after adding or replacing anything in public/ratings.

export const RATING_IMAGES = {
${body}
} as const;

export type RatingImagePath = keyof typeof RATING_IMAGES;
`,
);

console.log(`Wrote ${entries.length} entries to ${OUT_FILE}`);
